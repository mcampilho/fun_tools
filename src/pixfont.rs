/// Pixel rows of the glyph (one row above for capital accents, so 9 rows:
/// row 0 = capital accents, rows 1..8 = the letter, row 8 = descender).
/// Unknown characters become `?`.
pub fn glyph(c: char) -> Vec<Vec<bool>> {
    let parse = |s: &str| -> Vec<Vec<bool>> {
        let mut rows = vec![vec![false; 5]];
        rows.extend(s.split('|').map(|r| r.chars().map(|ch| ch == '#').collect()));
        rows
    };
    let find = |c: char| GLYPHS.iter().find(|(g, _)| *g == c).map(|(_, s)| parse(s));
    if let Some(g) = find(c) {
        return g;
    }
    let accent_row = |s: &str| s.chars().map(|ch| ch == '#').collect::<Vec<bool>>();
    if let Some(&(_, base, accent)) = ACCENTED.iter().find(|(a, ..)| *a == c) {
        let mut g = find(base).unwrap_or_else(|| find('?').unwrap());
        if base.is_uppercase() {
            g[0] = accent_row(accent);
        } else {
            // Lowercase: the accent goes where ascenders are; i loses its dot.
            g[1] = accent_row(accent);
            g[2] = vec![false; 5];
        }
        return g;
    }
    if c == 'ç' || c == 'Ç' {
        let mut g = find(if c == 'ç' { 'c' } else { 'C' }).unwrap();
        g[8] = accent_row("..#..");
        return g;
    }
    find('?').unwrap()
}

/// A line of text as a pixel bitmap: proportional (empty columns at the sides of
/// each glyph are dropped), one empty column between glyphs, empty rows trimmed
/// at the top and bottom (but the letters stay aligned).
pub fn bitmap(text: &str, gap: usize) -> Vec<Vec<bool>> {
    let mut rows: Vec<Vec<bool>> = vec![Vec::new(); 9];
    for (k, c) in text.chars().enumerate() {
        let g = glyph(c);
        let used: Vec<usize> = (0..5).filter(|&x| g.iter().any(|r| r[x])).collect();
        let (from, to) = match (used.first(), used.last()) {
            (Some(&a), Some(&b)) => (a, b + 1),
            _ => (0, 3), // space
        };
        for (y, row) in rows.iter_mut().enumerate() {
            if k > 0 {
                row.extend(std::iter::repeat_n(false, gap));
            }
            row.extend_from_slice(&g[y][from..to]);
        }
    }
    let used = |r: &Vec<bool>| r.iter().any(|&p| p);
    let top = rows.iter().position(used).unwrap_or(0);
    // Keep the cap/x-height part even when only lowercase or only capitals are used.
    let top = top.min(1);
    let bottom = rows.iter().rposition(used).map_or(rows.len(), |b| b + 1).max(8);
    rows[top..bottom].to_vec()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_are_well_formed() {
        for (c, s) in GLYPHS {
            let rows: Vec<&str> = s.split('|').collect();
            assert_eq!(rows.len(), 8, "{c}");
            assert!(rows.iter().all(|r| r.len() == 5), "{c}");
        }
        for c in (32u8..127).map(char::from) {
            assert!(GLYPHS.iter().any(|(g, _)| *g == c), "missing {c}");
        }
    }

    #[test]
    fn accents_and_bitmaps() {
        assert!(glyph('á')[1].iter().any(|&p| p));
        assert!(glyph('Ã')[0].iter().any(|&p| p));
        assert!(glyph('ç')[8].iter().any(|&p| p));
        let b = bitmap("Hi", 1);
        assert!(b.len() >= 7 && b.iter().all(|r| r.len() == b[0].len()));
    }
}
